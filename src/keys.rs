// Virtual key codes mapping and display helpers

pub fn vk_to_string(vk: u16) -> String {
    match vk {
        0x08 => "Backspace".to_string(),
        0x09 => "Tab".to_string(),
        0x0D => "Enter".to_string(),
        0x10 => "Shift".to_string(),
        0x11 => "Ctrl".to_string(),
        0x12 => "Alt".to_string(),
        0x13 => "Pause".to_string(),
        0x14 => "Caps Lock".to_string(),
        0x1B => "Escape".to_string(),
        0x20 => "Space".to_string(),
        0x21 => "Page Up".to_string(),
        0x22 => "Page Down".to_string(),
        0x23 => "End".to_string(),
        0x24 => "Home".to_string(),
        0x25 => "Left Arrow".to_string(),
        0x26 => "Up Arrow".to_string(),
        0x27 => "Right Arrow".to_string(),
        0x28 => "Down Arrow".to_string(),
        0x2D => "Insert".to_string(),
        0x2E => "Delete".to_string(),
        0x30..=0x39 => format!("{}", (vk as u8) as char),
        0x41..=0x5A => format!("{}", (vk as u8) as char),
        0x60..=0x69 => format!("Numpad {}", vk - 0x60),
        0x6A => "Numpad *".to_string(),
        0x6B => "Numpad +".to_string(),
        0x6D => "Numpad -".to_string(),
        0x6E => "Numpad .".to_string(),
        0x6F => "Numpad /".to_string(),
        0x70..=0x7B => format!("F{}", vk - 0x70 + 1),
        0xBA => "; (Semicolon)".to_string(),
        0xBB => "= (Equals)".to_string(),
        0xBC => ", (Comma)".to_string(),
        0xBD => "- (Minus)".to_string(),
        0xBE => ". (Period)".to_string(),
        0xBF => "/ (Slash)".to_string(),
        0xC0 => "` (Tilde)".to_string(),
        0xDB => "[ (Bracket)".to_string(),
        0xDC => "\\ (Backslash)".to_string(),
        0xDD => "] (Bracket)".to_string(),
        0xDE => "' (Quote)".to_string(),
        _ => format!("VK (0x{:02X})", vk),
    }
}

